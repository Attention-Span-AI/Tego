# run-tests.sh: the action's offline tests. No tego, no network, no GitHub. Scratch goes under $WORK.
#   1. shellcheck every script; actionlint the example workflow with this action as a local action
#   2. contract.sh: the generated contract for default and filled inputs, and refusals of bad inputs
#   3. check-writes.sh: grants over protected paths are refused, others pass
#   4. collect.sh -> render.sh -> post.sh -> gate.sh on real output of a governed run (testdata/)
#   5. the renderer with hostile names: nothing the agent named becomes Markdown, HTML, a link or a mention
# Usage: test/run-tests.sh [SHELLCHECK] [ACTIONLINT]
# Single quotes around Markdown with backticks are meant literally here.
# shellcheck disable=SC2016
set -euo pipefail
A="$(cd "$(dirname "$0")/.." && pwd)"
WORK="${WORK:-${TMPDIR:?set WORK or TMPDIR}/tego-action-tests}"
SC="${1:-${SHELLCHECK:-shellcheck}}"
AL="${2:-${ACTIONLINT:-actionlint}}"
mkdir -p "$WORK"
WORK="$(mktemp -d "$WORK/suite.XXXXXX")"
export WORK SHELLCHECK="$SC" ACTIONLINT="$AL"
# Network commands are blocked unless an individual case installs its local stub.
mkdir -p "$WORK/no-network"
for tool in curl gh cosign; do
  printf '#!/bin/sh\necho offline suite forbids network >&2\nexit 97\n' >"$WORK/no-network/$tool"
  chmod +x "$WORK/no-network/$tool"
done
export PATH="$WORK/no-network:$PATH"
pass=0
fail=0
ok() {
	pass=$((pass + 1))
	printf 'ok   %s\n' "$*"
}
no() {
	fail=$((fail + 1))
	printf 'FAIL %s\n' "$*"
}
check() { # check NAME CMD...
	local name="$1"
	shift
	if "$@" >"$WORK/last.out" 2>&1; then ok "$name"; else
		no "$name"
		sed 's/^/     /' "$WORK/last.out"
	fi
}
refuses() { # refuses NAME CMD...: CMD must fail
	local name="$1"
	shift
	if "$@" >"$WORK/last.out" 2>&1; then
		no "$name (it passed)"
		sed 's/^/     /' "$WORK/last.out"
	else ok "$name"; fi
}

# 1. lint
check "shellcheck scripts and tests (all severities)" "$SC" -x -s bash "$A"/scripts/*.sh "$A/test/run-tests.sh" "$A/test/make-sample.sh" "$A/test/fake-tego"
# actionlint reads a local action only inside a project, which it finds by a .git folder; an empty one is enough.
mkdir -p "$WORK/lintrepo/.git" "$WORK/lintrepo/.github/workflows" "$WORK/lintrepo/action"
cp "$A/action.yml" "$WORK/lintrepo/action/action.yml"
cat "$A/examples/agent-receipt.yml" >"$WORK/lintrepo/.github/workflows/agent-receipt.yml"
check "actionlint example workflow (this action as ./tego-receipt)" bash -c "cd '$WORK/lintrepo' && '$AL' -shellcheck '$SC' .github/workflows/agent-receipt.yml"
sed 's/on-refusal: warn/on-refusl: warn/' "$WORK/lintrepo/.github/workflows/agent-receipt.yml" >"$WORK/lintrepo/bad.yml"
refuses "actionlint catches a misspelt input (so it reads action.yml)" bash -c "cd '$WORK/lintrepo' && cp bad.yml .github/workflows/bad.yml && '$AL' .github/workflows/bad.yml; s=\$?; rm -f .github/workflows/bad.yml; exit \$s"
check "action.yml: composite, scripts present, no expression inside a run: line" python3 -I -c '
import sys, re, pathlib, yaml
a = pathlib.Path(sys.argv[1])
d = yaml.safe_load((a / "action.yml").read_text())
assert d["runs"]["using"] == "composite"
for st in d["runs"]["steps"]:
    if "run" in st:
        assert st.get("shell", "").startswith(("bash", "/bin/bash")), st
        assert "${{" not in st["run"], st["run"]
        for s in re.findall(r"scripts/([a-z-]+\.sh)", st["run"]):
            assert (a / "scripts" / s).is_file(), s
    else:
        assert re.search(r"@[0-9a-f]{40}$", st["uses"]), st["uses"]
' "$A"

# 2. contract.sh
export RUNNER_TEMP=/home/runner/work/_temp WORKSPACE=/home/runner/work/app/app
check "contract: defaults" bash -c "IN_PRESET='no-secrets,no-prod,repo-only-writes' IN_RECORD_READS=true '$A/scripts/contract.sh' >'$WORK/c1.yaml'"
check "contract: defaults text" diff -u - "$WORK/c1.yaml" <<'EOF'
# Generated by the tego receipt action from its inputs.
version: 0
name: ci-agent
extends: ["tego/ci@1", "tego/no-secrets", "tego/no-prod", "tego/repo-only-writes"]
reason:
  reads: "on"
fs:
  write: ["/home/runner/work/app/app/"]
  deny_read: ["/home/runner/work/_temp/"]
EOF
check "contract: filled" bash -c "IN_PRESET='no-secrets, no-prod' IN_WRITE=\$'src\n/tmp/' IN_ALLOW_HOSTS='registry.npmjs.org:443' IN_MODELS='anthropic api.anthropic.com 443' IN_ENV_PASS='ANTHROPIC_API_KEY, CI' IN_RECORD_READS=false '$A/scripts/contract.sh' >'$WORK/c2.yaml'"
check "contract: filled text" diff -u - "$WORK/c2.yaml" <<'EOF'
# Generated by the tego receipt action from its inputs.
version: 0
name: ci-agent
extends: ["tego/ci@1", "tego/no-secrets", "tego/no-prod"]
models:
  - {provider: "anthropic", host: "api.anthropic.com", port: 443}
fs:
  write: ["/home/runner/work/app/app/src/", "/tmp/"]
  deny_read: ["/home/runner/work/_temp/"]
net:
  allow: ["registry.npmjs.org:443"]
env:
  pass: ["ANTHROPIC_API_KEY", "CI"]
EOF
check "contract: generated files parse as YAML" python3 -I -c '
import sys
try:
    import yaml
except ImportError:
    print("pyyaml missing; skipped"); sys.exit(0)
for p in sys.argv[1:]:
    d = yaml.safe_load(open(p))
    assert d["version"] == 0 and d["fs"]["write"], p
' "$WORK/c1.yaml" "$WORK/c2.yaml"
refuses "contract: refuses a bad preset name" env IN_PRESET='no-secrets;rm' "$A/scripts/contract.sh"
refuses "contract: refuses a host without a port" env IN_ALLOW_HOSTS='example.com' "$A/scripts/contract.sh"
refuses "contract: refuses a bad variable name" env IN_ENV_PASS='A-B' "$A/scripts/contract.sh"
refuses "contract: refuses .. in a write folder" env IN_WRITE='../x' "$A/scripts/contract.sh"
refuses "contract: refuses a bad model line" env IN_MODELS='anthropic api.anthropic.com' "$A/scripts/contract.sh"
check "contract: a quote in a folder stays inside the string" bash -c "IN_WRITE='a\"b' '$A/scripts/contract.sh' | grep -F 'write: [\"/home/runner/work/app/app/a\\\"b/\"]'"

# 3. check-writes.sh
mk() { jq -n --args '{fs: [$ARGS.positional[] | {path: ., kind: "write"}] + [{path: "/x", kind: "deny_read"}]}' "$@"; }
mk /home/runner/work/app/app/ /dev/null >"$WORK/w-ok.json"
mk /home/runner/work/ >"$WORK/w-parent.json"
mk / >"$WORK/w-root.json"
mk /home/runner/work/_temp >"$WORK/w-same.json"
mk /home/runner/work/_tempfoo >"$WORK/w-prefix.json"
P=(/home/runner/work/_temp /home/runner/work/_actions/x/y /home/runner/.tego)
check "check-writes: workspace and /dev/null pass" "$A/scripts/check-writes.sh" "$WORK/w-ok.json" "${P[@]}"
refuses "check-writes: a parent of _temp is refused" "$A/scripts/check-writes.sh" "$WORK/w-parent.json" "${P[@]}"
refuses "check-writes: / is refused" "$A/scripts/check-writes.sh" "$WORK/w-root.json" "${P[@]}"
refuses "check-writes: _temp itself is refused" "$A/scripts/check-writes.sh" "$WORK/w-same.json" "${P[@]}"
check "check-writes: a sibling that shares a prefix passes" "$A/scripts/check-writes.sh" "$WORK/w-prefix.json" "${P[@]}"
check "check-writes: the sample's real compile table passes" "$A/scripts/check-writes.sh" "$A/testdata/compile.json" "${P[@]}"

# 4. collect -> render -> post -> gate on the governed run's real output
pipeline() { # pipeline NAME DATA_DIR [KEPT_RC]: runs the four scripts as the action would, in $WORK/NAME
	local data="$2" d="$WORK/$1" kept="${3:-0}"
	mkdir -p "$d/dir/evidence" "$d/dir/state" "$d/ledger/r-5cd05e60-0dmrm463r69xq-kpyavw"
	cp "$data/events.jsonl" "$d/ledger/r-5cd05e60-0dmrm463r69xq-kpyavw/events.jsonl"
	printf 'r-5cd05e60-0dmrm463r69xq-kpyavw a48c6844922d6ea567be6d901561116d2b79255471b10ef3851464867443f6a8\n' >"$d/anchor.txt"
	cp "$data/contract.yaml" "$data/compile.json" "$d/dir/evidence/"
	: >"$d/dir/state/runs-before.txt"
	printf '["%s", "/usr/bin", "/bin"]\n' "$d/dir" >"$d/dir/state/protected-paths.json"
	sha256sum "$A/test/fake-tego" | cut -d' ' -f1 >"$d/dir/state/binary-sha256"
	: >"$d/out"
	: >"$d/summary.md"
	(
		export DIR="$d/dir" TEGO="$A/test/fake-tego" FAKE_TEGO_DATA="$data" FAKE_ANCHOR="$d/anchor.txt" FAKE_KEPT_RC="$kept" LEDGER_ROOT="$d/ledger" AGENT_EXIT=0
		export GITHUB_OUTPUT="$d/out" GITHUB_STEP_SUMMARY="$d/summary.md" GITHUB_REPOSITORY=example/app GITHUB_RUN_ID=42
		export GITHUB_SERVER_URL=https://github.com GITHUB_WORKFLOW_REF=example/app/.github/workflows/agent-receipt.yml@refs/pull/7/merge
		export GITHUB_SHA=0123456789abcdef0123456789abcdef01234567 GITHUB_REF=refs/pull/7/merge GITHUB_EVENT_NAME=pull_request
		export GITHUB_RUN_ATTEMPT=1 GITHUB_JOB=agent GITHUB_ACTION=__tego-receipt RUNNER_OS=Linux RUNNER_ARCH=X64
		"$A/scripts/collect.sh"
		export WORKSPACE=/home/tego UNSIGNED_REASON="private: private/internal repositories default to unsigned"
		"$A/scripts/render.sh"
		export MD="$d/dir/evidence/receipt.md" DO_COMMENT=false DO_CHECK=false
		"$A/scripts/post.sh"
	)
}
check "pipeline on the sample run" pipeline sample "$A/testdata"
S="$WORK/sample"
check "collect: outputs" diff -u - <(grep -v '^markdown=' "$S/out") <<'EOF'
run-id=r-5cd05e60-0dmrm463r69xq-kpyavw
tier=landlock
refusals=1
head=a48c6844922d6ea567be6d901561116d2b79255471b10ef3851464867443f6a8
verified=true
EOF
check "collect: manifest ties head, ledger digest and contract hash" jq -e --arg e "$(sha256sum "$A/testdata/events.jsonl" | cut -d' ' -f1)" \
	'.head == "a48c6844922d6ea567be6d901561116d2b79255471b10ef3851464867443f6a8" and .events_sha256 == $e and .contract_hash == "9bc51d9305575273e74713c53bc0150dcf05c630bf8e4e35e28395a110a87abd" and .tier == "landlock" and .lines == 74 and .refusals == 1' "$S/dir/evidence/tego-ci.json"
# a receipt.json planted in the run folder makes `receipt --verify` exit 1 or 125 on an intact record: not the action's failure
for krc in 1 125; do
	check "pipeline when the kept receipt gives exit $krc but the record verifies" pipeline "kept$krc" "$A/testdata" "$krc"
	check "collect: the same manifest ($krc)" jq -e '.verified_on_runner == true and .lines == 74' "$WORK/kept$krc/dir/evidence/tego-ci.json"
done
unv="$WORK/unverified-data"
mkdir -p "$unv"
cp "$A/testdata/"*.json "$A/testdata/"*.jsonl "$A/testdata/"*.yaml "$unv/"
jq '.verified = false | .error = "chain broken"' "$A/testdata/verify.json" >"$unv/verify.json"
refuses "a record that does not verify still fails collection (kept receipt exit 1)" pipeline unverified "$unv" 1
check "post: the job summary holds the receipt" cmp "$S/dir/evidence/receipt.md" "$S/summary.md"
for want in '### Incomplete: Tego receipt' 'head `a48c6844922d6ea567be6d901561116d2b79255471b10ef3851464867443f6a8`' 'fs.deny_read[~/k2-secret.txt]' \
  '| Tier | `landlock` |' 'Wrote `k2-worker/result.json`' 'Reads: this tier records read activity' '`tokens`: `not recorded: model traffic capture was off for this run`' \
  'Unsigned (`private: private/internal repositories default to unsigned`)' ; do
	check "render: shows $want" grep -qF -- "$want" "$S/dir/evidence/receipt.md"
done
check "render: the first line is the hashed comment marker" bash -c "head -n1 '$S/dir/evidence/receipt.md' | grep -Eq '^<!-- tego-receipt:[0-9a-f]{64} -->$'"

gate() { env RUN_ID=r-1 "$@" "$A/scripts/gate.sh"; }
check "gate: clean run passes" gate AGENT_EXIT=0 REFUSALS=0 VERIFIED=true IN_ON_REFUSAL=warn
check "gate: refusal with warn passes" gate AGENT_EXIT=0 REFUSALS=2 VERIFIED=true IN_ON_REFUSAL=warn
refuses "gate: refusal with fail fails" gate AGENT_EXIT=0 REFUSALS=2 VERIFIED=true IN_ON_REFUSAL=fail
refuses "gate: unverified record fails" gate AGENT_EXIT=0 REFUSALS=0 VERIFIED=false IN_ON_REFUSAL=warn
check "gate: the agent's exit code comes back" bash -c "RUN_ID=r-1 AGENT_EXIT=3 REFUSALS=0 VERIFIED=true '$A/scripts/gate.sh'; [ \$? = 3 ]"

# 5. hostile names: every agent-chosen string must stay inside a code span
H="$WORK/hostile-data"
mkdir -p "$H"
cp "$A/testdata/"*.json "$A/testdata/"*.jsonl "$A/testdata/"*.yaml "$H/"
jq '.refusals.list[0].target = "/home/tego/x`<img src=x onerror=alert(1)>`|@octocat [y](https://evil.example)\n# H1"
  | .refusals.by_rule[0].rule = "fs.deny_read[`|<b>bold</b>|`]"
  | .files.written = ["/home/tego/@octocat` <script>x</script>", "/home/tego/a|b"]
  | .command = ["sh", "-c", "echo `id` | tee [z](http://evil.example)"]' "$A/testdata/receipt.json" >"$H/receipt.json"
check "pipeline on hostile names" pipeline hostile "$H"
check "hostile: no HTML, link or mention outside code spans" python3 -I -c '
import re, sys
md = open(sys.argv[1]).read()
outside = re.sub(r"`[^`\n]*`", "", md)
bad = [p for p in ("<img", "<script", "<b>", "@octocat", "evil.example", "\n# H1") if p in outside]
assert not bad, bad
' "$WORK/hostile/dir/evidence/receipt.md"
check "hostile: table rows keep their cell count" python3 -I -c '
import sys
rows = [l for l in open(sys.argv[1]) if l.startswith("| ") and "Rule" not in l and "---" not in l]
for l in rows:
    cells = l.replace("\\|", "").count("|")
    assert cells in (3, 4, 5, 8), (cells, l)
' "$WORK/hostile/dir/evidence/receipt.md"

check 'review, permissions, interpolation and lab cases' python3 -I "$A/test/review-tests.py"
check 'post-run execution trust boundary' python3 -I "$A/test/security-tests.py"
check 'fresh verifier decision and rerun regressions' python3 -I "$A/test/verifier-fix-tests.py"
check 'launcher-owned status and safe copy boundaries' python3 -I "$A/test/status-tests.py"
check 'signing policy, consent, teardown and workflow boundaries' python3 -I "$A/test/signing-tests.py"
check 'signing decisions with unavailable repository and PR APIs' python3 -I "$A/test/signing-policy-tests.py"
check 'pinned tool, trust and authenticated release boundaries' python3 -I "$A/test/trust-tests.py"
check 'handoff and failure boundary cases' python3 -I "$A/test/boundary-tests.py"

printf '\n%d legacy/integration checks passed, %d failed\n' "$pass" "$fail"
[ "$fail" = 0 ]
