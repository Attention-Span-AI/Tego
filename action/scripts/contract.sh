export PATH=/usr/bin:/bin
unset BASH_ENV ENV PROMPT_COMMAND CDPATH GLOBIGNORE
if [ "${1:-}" = --tego-ci-clean ]; then
  shift
else
  exec /usr/bin/python3 -I "$(/usr/bin/dirname "$0")/environment.py" "$0" "$@"
fi


#
# contract.sh: prints the contract the action generates from its inputs, as YAML on stdout. It reads only its
# environment and starts no tego, so it can be tested anywhere.
#   IN_PRESET        comma list of tego presets (no-secrets, no-prod, repo-only-writes)
#   IN_WRITE         folders the agent may write, one per line (empty: WORKSPACE)
#   IN_ALLOW_HOSTS   host:port entries, one per line
#   IN_MODELS        "provider host port", one per line
#   IN_ENV_PASS      variable names, one per line or comma separated
#   IN_RECORD_READS  true adds reason.reads "on"
#   WORKSPACE        the workspace (absolute)
#   RUNNER_TEMP      the runner's temp folder, which the contract keeps the agent from reading
# Every value is written as a JSON string, which YAML reads as a double-quoted scalar.
set -euo pipefail
# shellcheck source-path=SCRIPTDIR source=lib.sh
. "$(/usr/bin/dirname "$0")/lib.sh"

: "${WORKSPACE:?}" "${RUNNER_TEMP:?}"
q() { /usr/bin/jq -Rn --arg s "$1" '$s'; }

absdir() { # absdir PATH: an absolute folder with one trailing slash; relative paths are under WORKSPACE
	local p="$1"
	case "$p" in
	/*) ;;
	*) p="$WORKSPACE/$p" ;;
	esac
	p="${p%/}/"
	case "$p" in
	*/../* | */./*) die "write entry '$1': no . or .. components, please" ;;
	esac
	printf '%s' "$p"
}

presets=("tego/ci@1")
while IFS= read -r p; do
	[[ "$p" =~ ^[a-z][a-z-]*(@[0-9]+)?$ ]] || die "preset '$p' is not a preset name"
	presets+=("tego/$p")
done < <(words "${IN_PRESET:-}")

writes=()
while IFS= read -r w; do writes+=("$(absdir "$w")"); done < <(words "${IN_WRITE:-}")
[ "${#writes[@]}" -gt 0 ] || writes=("$(absdir "$WORKSPACE")")

hostre='^[][A-Za-z0-9.*:-]+:[0-9]+$' # a name, a wildcard name, an IPv4 or a bracketed IPv6, then :port
hosts=()
while IFS= read -r h; do
	[[ "$h" =~ $hostre ]] || die "allow-hosts entry '$h' is not host:port"
	hosts+=("$h")
done < <(words "${IN_ALLOW_HOSTS:-}")

models=()
while IFS= read -r line; do
	read -r provider host port extra <<<"$line"
	[ -z "${extra:-}" ] || die "models line '$line': give provider host port"
	[[ "${provider:-}" =~ ^[a-z0-9-]+$ && "${host:-}" =~ ^[A-Za-z0-9.-]+$ && "${port:-}" =~ ^[0-9]+$ ]] ||
		die "models line '$line': give provider host port, such as: anthropic api.anthropic.com 443"
	models+=("{provider: $(q "$provider"), host: $(q "$host"), port: $port}")
done < <(printf '%s\n' "${IN_MODELS:-}" | /usr/bin/sed '/^[[:space:]]*$/d')

envs=()
while IFS= read -r e; do
	[[ "$e" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || die "env-pass entry '$e' is not a variable name"
	envs+=("$e")
done < <(words "${IN_ENV_PASS:-}")

list() { # list ITEMS...: a YAML flow list of JSON strings
	local first=1 s="["
	for i in "$@"; do
		[ $first = 1 ] || s+=", "
		s+="$(q "$i")"
		first=0
	done
	printf '%s]' "$s"
}

echo "# Generated by the tego receipt action from its inputs."
echo "version: 0"
echo "name: ci-agent"
[ "${#presets[@]}" -eq 0 ] || echo "extends: $(list "${presets[@]}")"
if [ "${IN_RECORD_READS:-true}" = true ]; then
	echo "reason:"
	echo '  reads: "on"'
fi
if [ "${#models[@]}" -gt 0 ]; then
	echo "models:"
	for m in "${models[@]}"; do echo "  - $m"; done
fi
echo "fs:"
echo "  write: $(list "${writes[@]}")"
echo "  deny_read: $(list "${RUNNER_TEMP%/}/")"
if [ "${#hosts[@]}" -gt 0 ]; then
	echo "net:"
	echo "  allow: $(list "${hosts[@]}")"
fi
if [ "${#envs[@]}" -gt 0 ]; then
	echo "env:"
	echo "  pass: $(list "${envs[@]}")"
fi
