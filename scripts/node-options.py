"""Capture Node's versioned CLI inventories and generate its forwarded V8 list.

Usage: scripts/node-options.py [--check] NODE_20_19_4 NODE_22_21_1
The native options and alias semantics remain reviewed data in rows/interp.go.
Runtime version attestation uses the captured standalone executable SHA-256 hashes.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
ROWS = ROOT / "pkg/policy/execmatch/rows"
DUMP = """const {internalBinding}=require('internal/test/binding');
const b=internalBinding('options'), i=b.getCLIOptionsInfo();
const n=Object.fromEntries(Object.entries(b.types).map(([k,v])=>[v,k]));
process.stdout.write(JSON.stringify({
options:Object.fromEntries([...i.options].filter(([k])=>k.startsWith('--')).map(([k,o])=>[k,n[o.type]])),
aliases:Object.fromEntries(i.aliases)}));"""
# These stay unknown. The first three had different arities in older Node;
# stack-trace-limit changes from V8 forwarding in 20 to a native integer in 22.
UNKNOWN = {"experimental-specifier-resolution", "es-module-specifier-resolution",
           "http-parser", "stack-trace-limit"}


def capture(binary, version):
    def run(*args):
        return subprocess.check_output([binary, *args], text=True).strip()
    assert run("--version") == version, f"expected {version}: {binary}"
    data = json.loads(run("--expose-internals", "--no-warnings", "-e", DUMP))
    data["version"] = version
    dynamic = subprocess.check_output(["readelf", "-d", binary], text=True)
    assert "libnode.so" not in dynamic, "a libnode loader hash does not identify the runtime; use a standalone Node build"
    data["build_sha256"] = hashlib.file_digest(open(binary, "rb"), "sha256").hexdigest()
    data["help"] = [line.strip() for line in run("--help").splitlines()
                    if re.match(r"^  (?:--|-[A-Za-z],)", line)]
    data["environment"] = json.loads(run(
        "-p", "JSON.stringify([...process.allowedNodeEnvironmentFlags].sort())"))
    data["v8"] = dict(re.findall(
        r"^  --([\w-]+) \([^\n]*\)\n\s+type: (\w+)", run("--v8-options"), re.M))
    assert len(data["v8"]) > 500, "incomplete V8 inventory"
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("node20")
    parser.add_argument("node22")
    args = parser.parse_args()
    inventories = [capture(b, v) for b, v in
                   [(args.node20, "v20.19.4"), (args.node22, "v22.21.1")]]
    outputs = {}
    for data in inventories:
        outputs[ROWS / "testdata" / ("node-" + data["version"] + ".json")] = (
            json.dumps(data, indent=2, sort_keys=True) + "\n")
    native = set(UNKNOWN)
    v8 = set()
    for data in inventories:
        native.update(k.removeprefix("--") for k in data["options"])
        native.update(k.removeprefix("--") for k in data["aliases"])
        v8.update(data["v8"])
    names = sorted(v8 - native)
    outputs[ROWS / "node_v8_generated.go"] = (
        "// SPDX-License-Identifier: Apache-2.0\n\n"
        "// Code generated by scripts/node-options.py; DO NOT EDIT.\n"
        "// Source: node v20.19.4 and v22.21.1 --v8-options (linux x64).\n"
        "// These options are forwarded by Node without consuming the next token,\n"
        "// regardless of V8's own type. Native options take precedence; the\n"
        "// version-dependent stack-trace-limit stays unknown.\n\n"
        "package rows\n\nvar nodeV8Flags = []string{\n" +
        "".join('\t"' + name + '",\n' for name in names) + "}\n")
    outputs[ROWS / "node_builds_generated.go"] = (
        "// SPDX-License-Identifier: Apache-2.0\n\n"
        "// Code generated by scripts/node-options.py; DO NOT EDIT.\n"
        "// Standalone Linux x64 builds whose CLI inventories were captured.\n\n"
        "package rows\n\nimport \"encoding/hex\"\n\n"
        "// NodeBuildVersion identifies an exact inventoried executable build.\n"
        "// Unknown builds (including shared-libnode loaders) stay unknown.\n"
        "func NodeBuildVersion(sum [32]byte) string {\n\tswitch hex.EncodeToString(sum[:]) {\n" +
        "".join('\tcase \"' + d["build_sha256"] + '\":\n\t\treturn \"' + d["version"][1:] + '\"\n' for d in inventories) +
        '\t}\n\treturn \"\"\n}\n')
    for path, content in outputs.items():
        if args.check:
            assert path.read_text() == content, f"stale: {path}"
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_text(content)
    print(f"Node 20/22 inventories verified; {len(names)} additional V8 options")


if __name__ == "__main__":
    main()
