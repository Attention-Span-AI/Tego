#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
#
# fetch-clang.sh — put a clang/LLVM that can build bpf/*.bpf.c under $TEGO_VM_CACHE without root, and
# print the path to pass as `make gen CLANG=...`.
#
# Why it exists: `make gen` (bpf2go, internal/bpf/gen.go) needs clang and llvm-strip, and the BPF
# objects it produces are what every tegobpf build embeds; a box with no clang and no sudo cannot
# produce them, so the tier-2/3 and uprobe suites cannot even be compiled there. This downloads the
# distro's own clang-N, llvm-N and their libraries with `apt-get download` (no root), extracts them
# with `dpkg-deb -x`, fetches whatever shared library the host lacks (ldd, round by round from the
# packages' direct Depends), and writes two small wrappers — bin/clang and bin/llvm-strip — that set
# LD_LIBRARY_PATH for the extracted tree. gen.go's lines say `-cc clang`, and bpf2go derives
# `llvm-strip` from that name, so the Makefile's CLANG=<dir>/clang puts <dir> first on PATH and both
# resolve to these wrappers. bpf/README.md records clang 20.1.8 as the version the objects were made
# with; Ubuntu 25.10's default clang is that version.
#
# Usage: test/vm/fetch-clang.sh            prints the clang wrapper's path (fetching on first use)
# Environment: TEGO_VM_CACHE (default ~/.cache/tego-vm), TEGO_CLANG_VERSION (default: the major
#   version the distro's `clang` package depends on).
# Exit code: 0 with the path on stdout; 97 when the toolchain cannot be fetched or does not run.
set -euo pipefail

CACHE="${TEGO_VM_CACHE:-$HOME/.cache/tego-vm}"
CROOT="$CACHE/clang"
log() { echo "fetch-clang: $*" >&2; }
env_fail() {
	echo "fetch-clang: FAIL: $*" >&2
	exit 97
}

for tool in apt-get apt-cache dpkg-deb dpkg-query ldd; do
	command -v "$tool" >/dev/null 2>&1 || env_fail "$tool is not on PATH"
done

V="${TEGO_CLANG_VERSION:-}"
if [ -z "$V" ]; then
	V="$(apt-cache depends clang 2>/dev/null | sed -n 's/^ *Depends: clang-\([0-9][0-9]*\)$/\1/p' | head -1)"
	[ -n "$V" ] || env_fail "cannot tell which clang-N the distro's clang package means; set TEGO_CLANG_VERSION"
fi
LLVM="$CROOT/root/usr/lib/llvm-$V"
LIBS="$LLVM/lib:$CROOT/root/usr/lib/x86_64-linux-gnu:$CROOT/root/lib/x86_64-linux-gnu"
WRAP="$CROOT/bin"

if [ -f "$CROOT/.ready-$V" ] && [ -x "$WRAP/clang" ]; then
	echo "$WRAP/clang"
	exit 0
fi

mkdir -p "$CACHE/debs/clang" "$CROOT/root"
exec 9>"$CACHE/.clang-lock"
flock 9

installed() { dpkg-query -W -f='${db:Status-Abbrev}' "$1" 2>/dev/null | grep -q '^ii'; }
fetch() {
	local p deb
	for p in "$@"; do
		deb="$(find "$CACHE/debs/clang" -maxdepth 1 -name "${p}_*.deb" -print -quit)"
		if [ -z "$deb" ]; then
			(cd "$CACHE/debs/clang" && apt-get download "$p" >/dev/null 2>&1) || env_fail "apt-get download $p failed"
			deb="$(find "$CACHE/debs/clang" -maxdepth 1 -name "${p}_*.deb" -print -quit)"
		fi
		dpkg-deb -x "$deb" "$CROOT/root"
		echo "$p" >>"$CROOT/.fetched"
	done
}
missing() {
	local b
	for b in clang llvm-objcopy; do
		LD_LIBRARY_PATH="$LIBS" ldd "$LLVM/bin/$b" 2>/dev/null | awk '/not found/ {print $1}'
	done | sort -u
}

log "fetching clang-$V and llvm-$V into $CROOT/root"
fetch "clang-$V" "libclang-cpp$V" "libllvm$V" "libclang-common-$V-dev" "llvm-$V" "libclang1-$V"
for round in 1 2 3 4 5; do
	m="$(missing)"
	[ -n "$m" ] || break
	want=""
	# shellcheck disable=SC2046 # one argument per fetched package name
	for p in $(apt-cache depends --no-recommends --no-suggests --no-conflicts --no-breaks --no-replaces \
		--no-enhances $(sort -u "$CROOT/.fetched") 2>/dev/null |
		awk '$1 ~ /^\|?(Pre)?Depends:$/ && $2 !~ /^</ && $2 !~ /:/ {print $2}' | sort -u); do
		installed "$p" || grep -qx "$p" "$CROOT/.fetched" || want="$want $p"
	done
	# $(echo $m) joins the missing libraries' lines with single spaces.
	# shellcheck disable=SC2086,SC2116
	[ -n "$want" ] || env_fail "clang still lacks $(echo $m) and no uninstalled dependency is left to fetch"
	# shellcheck disable=SC2086,SC2116
	log "round $round: clang lacks $(echo $m); fetching$want"
	# shellcheck disable=SC2086
	fetch $want
done
[ -z "$(missing)" ] || env_fail "clang still lacks shared libraries: $(missing | tr '\n' ' ')"

mkdir -p "$WRAP"
for t in clang llvm-strip; do
	cat >"$WRAP/$t" <<-EOF
		#!/bin/sh
		# Generated by test/vm/fetch-clang.sh: the extracted $t-$V, with its libraries.
		LD_LIBRARY_PATH="$LIBS\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}" exec "$LLVM/bin/$t" "\$@"
	EOF
	chmod 0755 "$WRAP/$t"
done
"$WRAP/clang" --version >/dev/null 2>&1 || env_fail "the extracted clang does not run"
echo 'int x;' | "$WRAP/clang" -target bpf -O2 -g -c -x c - -o /dev/null 2>/dev/null ||
	env_fail "the extracted clang cannot compile for -target bpf"
touch "$CROOT/.ready-$V"
log "$("$WRAP/clang" --version | head -1)"
echo "$WRAP/clang"
