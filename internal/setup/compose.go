// Marker opens every contract init writes; internal/cli keeps the same text so a second init recognises its own file.
const Marker = "# Generated by tego init"

// Options is what `tego init --preset` was asked for.
type Options struct {
	// Presets is the --preset list, each a preset name with or without the tego/ prefix.
	Presets []string
	// Writes is each --write folder, as typed: relative to Dir, absolute, or ~/ for Home.
	Writes []string
	// Hosts is each --allow-host: host, host:port, @group or unix:/path.
	Hosts []string
	// Command is --command, one line; empty writes a short demo command.
	Command string
	// Name is the agent id, already checked by the caller.
	Name string
	// Dir is the project directory, absolute, with its symlinks resolved (filepath.EvalSymlinks): Create opens it with
	// no symlink followed, so a link in its path is refused.
	Dir string
	// Home expands a leading ~/ in a --write folder; empty leaves it as typed.
	Home string
	// Pass are the variables the agent needs from the shell that starts it (env.pass), AskRead the paths a person is
	// asked about before each read (fs.ask_read: relative to Dir, absolute, or ~/ for Home).
	Pass, AskRead []string
	// AgentNeeds adds what the command's agent needs to run under the presets, where they restrict it: Claude Code's
	// or Codex's own folder (in the project), its socket folder, its model host and its login variables
	// (agentNeeds). The dashboard's New policy sets it; tego init does not.
	AgentNeeds bool
}

// Result is the composed contract and what the caller does around it.
type Result struct {
	// Contract is the agent.yaml bytes.
	Contract []byte
	// MakeDirs are the absolute folders the contract's fs.write names that do not exist yet; the caller creates them
	// before compiling, since every fs entry must name an existing path (SEMANTICS §2 Identity).
	MakeDirs []string
	// Ignore are the .gitignore lines the generated folders under .tego/ need.
	Ignore []string
	// Notes are lines the caller prints after writing: what each preset promises and what the user still adds.
	Notes []string
	// Presets are the presets the contract extends, by name, in catalog order.
	Presets []string
	// Diagnostics are what compiling Contract found, set by Draft only (Compose leaves it nil): errors and
	// warnings, as `tego compile --offline` prints them.
	Diagnostics []agent.Diagnostic
	// OK is set by Draft: no diagnostic is an error, so the contract can be written.
	OK bool
	// Grants is, by preset name, what AgentNeeds added to the contract past what the preset's name says: a chosen
	// preset's promise then holds with these exceptions, which the dashboard states beside its label.
	Grants map[string][]string

	// makeEntries are the fs.write values whose folder is in MakeDirs, for Draft's filter.
	makeEntries []string
}

// grant records value under preset (Grants).
func (r *Result) grant(preset, value string) {
	if r.Grants == nil {
		r.Grants = map[string][]string{}
	}
	r.Grants[preset] = append(r.Grants[preset], value)
}

// UsageError is a mistake in the options: the caller exits 2 with its text.
type UsageError struct{ Msg string }

func (e *UsageError) Error() string { return e.Msg }

func usagef(format string, a ...any) error { return &UsageError{Msg: fmt.Sprintf(format, a...)} }

// IsUsage reports whether err is a UsageError.
func IsUsage(err error) bool {
	var u *UsageError
	return errors.As(err, &u)
}

// ParsePresets reads a comma list of preset names into catalog order, each once. An unknown name is a usage error
// listing the known ones.
func ParsePresets(list []string) ([]presets.Preset, error) {
	want := map[string]bool{}
	for _, item := range list {
		for name := range strings.SplitSeq(item, ",") {
			name = strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(name), presets.Prefix))
			if name == "" {
				continue
			}
			found := false
			for _, p := range presets.List() {
				if p.Name == name {
					found = true
				}
			}
			if !found {
				return nil, usagef("unknown preset %q; the presets are %s", name, strings.Join(KnownPresets(), ", "))
			}
			want[name] = true
		}
	}
	if len(want) == 0 {
		return nil, usagef("--preset names no preset; the presets are %s", strings.Join(KnownPresets(), ", "))
	}
	var out []presets.Preset
	for _, p := range presets.List() {
		if want[p.Name] {
			out = append(out, p)
		}
	}
	return out, nil
}

// KnownPresets is every preset's name, in catalog order.
func KnownPresets() []string {
	var names []string
	for _, p := range presets.List() {
		names = append(names, p.Name)
	}
	return names
}

// entry is one generated list line and the comment saying why it is there.
type entry struct{ value, why string }

// Compose builds the contract for o. It reads Dir for project markers and the existence of each --write folder,
// and writes nothing.
func Compose(o Options) (*Result, error) {
	ps, err := ParsePresets(o.Presets)
	if err != nil {
		return nil, err
	}
	has := func(name string) bool {
		return slices.ContainsFunc(ps, func(p presets.Preset) bool { return p.Name == name })
	}
	res := &Result{}

	// fs.write: the --write folders, then (when writes are restricted at all) the folders the markers imply and TMPDIR.
	var writes []entry
	var firstWrite string
	for _, w := range o.Writes {
		e, mk, err := writeEntry(o, w)
		if err != nil {
			return nil, err
		}
		if firstWrite == "" {
			firstWrite = e
		}
		writes = appendEntry(writes, entry{e, "--write"})
		if mk != "" {
			res.makeDir(mk, e)
		}
		if s := secretFolderIn(o.Home, o.Dir, e); s != "" {
			res.Notes = append(res.Notes, fmt.Sprintf("  --write %s reaches ~/%s, a folder the built-in deny_read list keeps from the agent's reads; check that the agent needs to write there", w, s))
		}
	}
	envSet := []entry{}
	if has("repo-only-writes") || len(writes) > 0 {
		eco := ecosystem(o.Dir)
		if has("repo-only-writes") && len(writes) == 0 && len(eco.writes) == 0 {
			return nil, usagef("repo-only-writes needs the folders the agent may write: add --write <dir> (for example --write src/ --write tests/)")
		}
		for _, e := range eco.writes {
			writes = appendEntry(writes, e)
			mk := filepath.Join(o.Dir, filepath.FromSlash(strings.TrimPrefix(e.value, "./")))
			if !exists(mk) {
				res.makeDir(mk, e.value)
			}
		}
		envSet = append(envSet, eco.env...)
		res.Ignore = append(res.Ignore, eco.ignore...)
		tmp := filepath.Join(o.Dir, ".tego", "tmp")
		writes = appendEntry(writes, entry{"./.tego/tmp/", "TMPDIR: the agent's temporary files stay in the project"})
		envSet = append(envSet, entry{"TMPDIR=" + tmp, "TMPDIR inside the writable ./.tego/tmp/"})
		if !exists(tmp) {
			res.makeDir(tmp, "./.tego/tmp/")
		}
		res.Ignore = append(res.Ignore, ".tego/tmp/")
	}

	// net.allow: each --allow-host, a group expanded.
	var hosts []entry
	for _, h := range o.Hosts {
		es, err := hostEntries(h)
		if err != nil {
			return nil, err
		}
		for _, e := range es {
			hosts = appendEntry(hosts, e)
		}
	}

	command := o.Command
	demo := false
	if strings.TrimSpace(command) == "" {
		command, demo = demoCommand(has, firstWrite), true
	}
	var pass, askRead []entry
	for _, v := range o.Pass {
		if v = strings.TrimSpace(v); v != "" {
			pass = appendEntry(pass, entry{v, "a variable the agent needs"})
		}
	}
	for _, a := range o.AskRead {
		if a = strings.TrimSpace(a); a != "" {
			askRead = appendEntry(askRead, entry{askPath(o, a), "a person decides each read"})
		}
	}
	if o.AgentNeeds && !demo { // the tego init note about ~/.claude below is then already handled
		need := agentNeedsOf(o, commandArgv(command))
		// grant adds es to list, naming under preset those the list did not hold when the preset is chosen.
		grant := func(preset string, list, es []entry) []entry {
			for _, e := range es {
				before := len(list)
				if list = appendEntry(list, e); len(list) > before && has(preset) {
					res.grant(preset, e.value)
				}
			}
			return list
		}
		if has("repo-only-writes") || len(o.Writes) > 0 {
			writes = grant("repo-only-writes", writes, need.writes)
			for _, w := range need.writes {
				if mk := need.made[w.value]; mk != "" && !exists(mk) {
					res.makeDir(mk, w.value)
				}
			}
			envSet = append(envSet, need.env...)
			res.Ignore = append(res.Ignore, need.ignore...)
		}
		if has("no-prod") || len(hosts) > 0 {
			hosts = grant("no-prod", hosts, need.hosts)
		}
		if has("no-secrets") || len(pass) > 0 {
			pass = grant("no-secrets", pass, need.pass)
		}
	}
	res.Contract = render(o.Name, ps, commandArgv(command), demo, writes, hosts, envSet, pass, askRead)
	for _, p := range ps {
		res.Presets = append(res.Presets, p.Name)
		res.Notes = append(res.Notes, fmt.Sprintf("  %s@%d: %s", p.Ref(), p.Revision, p.Promise))
	}
	if has("no-secrets") {
		res.Notes = append(res.Notes, "  no-secrets passes only an allow-list of variables: an agent that needs its API key adds it to env.pass (the file says where)")
	}
	if has("no-prod") && len(hosts) == 0 {
		res.Notes = append(res.Notes, "  no-prod with no --allow-host refuses every host, the agent's model included: add --allow-host <host> or a models: entry")
	}
	if has("repo-only-writes") && !(o.AgentNeeds && len(agentNeedsOf(o, commandArgv(command)).writes) > 0) {
		res.Notes = append(res.Notes, "  repo-only-writes: an agent that keeps state in your home (Claude Code's ~/.claude) needs --write for that folder too")
	}
	return res, nil
}

// render writes the contract: a header saying what each preset promises and what is always on, then each section
// opened by a comment saying why it is there and each generated entry closed by a comment naming the flag or the
// project marker it came from. Lists are aligned so the reasons read as a column. The bytes are deterministic for
// the same inputs (golden tests in testdata/compose/).
func render(name string, ps []presets.Preset, argv []string, demo bool, writes, hosts, envSet, pass, askRead []entry) []byte {
	var b strings.Builder
	var names, refs []string
	has := map[string]bool{}
	for _, p := range ps {
		names = append(names, p.Name)
		refs = append(refs, p.Ref())
		has[p.Name] = true
	}
	fmt.Fprintf(&b, "%s --preset %s.\n", Marker, strings.Join(names, ","))
	b.WriteString("# Edit freely: `tego compile agent.yaml` shows what will be enforced, and `tego compile --merged agent.yaml`\n")
	b.WriteString("# prints the one rule file with every preset laid in (docs/user/presets.md).\n#\n")
	b.WriteString("# What the presets promise:\n")
	for _, p := range ps {
		fmt.Fprintf(&b, "#   %s@%d: %s.\n", p.Ref(), p.Revision, p.Promise)
	}
	b.WriteString("#\n# Always on, preset or not: the host's local daemon sockets (docker, the D-Bus bus, ssh-agent) are refused,\n")
	b.WriteString("# since host_sockets is not set (ADR 0070), and the agent cannot gain privilege: no_new_privs is set on every\n")
	b.WriteString("# run and setuid binaries do not raise it.\n\n")
	b.WriteString("version: 0\n")
	fmt.Fprintf(&b, "name: %s\n\n", strconv.Quote(name))

	b.WriteString("# The presets this contract builds on, in a fixed order. Their lists and this file's add up; pin one to the\n")
	b.WriteString("# revision you reviewed with tego/<preset>@<n> to keep later releases from changing it.\n")
	fmt.Fprintf(&b, "extends: [%s]\n\n", strings.Join(refs, ", "))

	if demo {
		b.WriteString("# The program tego starts. This is a short demo of the presets in sh; replace it with your agent, for\n")
		b.WriteString("# example [\"claude\"] or [\"codex\"].\n")
	} else {
		b.WriteString("# The program tego starts (--command).\n")
	}
	if demo && len(argv) == 3 && argv[0] == "/bin/sh" && strings.Contains(argv[2], "\n") {
		// The demo script reads best as a literal block, one shell line per line; its lines are init's own, none
		// empty or indented, so the block's indentation is unambiguous. A --command line stays one quoted string.
		b.WriteString("command:\n  - /bin/sh\n  - -c\n  - |\n")
		for line := range strings.SplitSeq(argv[2], "\n") {
			fmt.Fprintf(&b, "    %s\n", line)
		}
	} else {
		quoted := make([]string, len(argv))
		for i, a := range argv {
			quoted[i] = strconv.Quote(a)
		}
		fmt.Fprintf(&b, "command: [%s]\n", strings.Join(quoted, ", "))
	}

	if len(writes) > 0 {
		b.WriteString("\n# Where the agent may write; a folder covers everything beneath it.")
		if has["repo-only-writes"] {
			b.WriteString(" repo-only-writes refuses every\n# write outside these entries.\n")
		} else {
			b.WriteString(" Every write outside these entries is\n# refused.\n")
		}
		b.WriteString("fs:\n  write:\n")
		writeList(&b, "    ", writes)
	}
	if len(askRead) > 0 {
		if len(writes) == 0 {
			b.WriteString("\nfs:\n")
		}
		b.WriteString("  # A person is asked before each read of these (the dashboard's Approvals, or tego ask).\n")
		b.WriteString("  ask_read:\n")
		writeList(&b, "    ", askRead)
	}

	switch {
	case len(hosts) > 0:
		b.WriteString("\n# The hosts the agent may reach.")
		if has["no-prod"] {
			b.WriteString(" no-prod refuses every other host.")
		}
		b.WriteString("\nnet:\n  allow:\n")
		writeList(&b, "    ", hosts)
	case has["no-prod"]:
		b.WriteString("\n# No --allow-host was given, so no-prod refuses every host, the agent's model included. Name the ones it\n")
		b.WriteString("# needs, for example:\n# net:\n#   allow:\n#     - \"api.example.com:443\"\n")
	}

	// env: is written only with an entry under it: a key with only comments beneath it is a YAML null.
	if len(pass) > 0 {
		b.WriteString("\nenv:\n  # Variables the agent gets from the shell that starts it, on top of the presets' list.\n  pass:\n")
		writeList(&b, "    ", pass)
		if len(envSet) > 0 {
			b.WriteString("  # Variables tego sets for the agent, so its temporary files and caches land in folders it may write.\n")
			b.WriteString("  set:\n")
			for _, e := range envSet {
				k, v, _ := strings.Cut(e.value, "=")
				fmt.Fprintf(&b, "    # %s\n    %s: %s\n", e.why, k, strconv.Quote(v))
			}
		}
	}
	if len(askRead) > 0 {
		b.WriteString("\n# How long an ask waits for a person before it is refused.\nask:\n  timeout: 5m\n")
		b.WriteString("\n# A read held for a person is a Landlock feature: pin the tier so the asks are enforced, not refused.\ntier: landlock\n")
	}
	if len(pass) > 0 {
		return []byte(b.String())
	}
	if has["no-secrets"] && len(envSet) == 0 {
		b.WriteString("\n# no-secrets passes only its allow-list of variables (PATH, HOME, LANG and the like). Add each name your\n")
		b.WriteString("# agent needs, its API key for example (the lists add up):\n")
		b.WriteString("# env:\n#   pass:\n#     - ANTHROPIC_API_KEY\n")
	}
	if len(envSet) > 0 {
		b.WriteString("\nenv:\n")
		if has["no-secrets"] {
			b.WriteString("  # no-secrets passes only its allow-list of variables (PATH, HOME, LANG and the like). Add each name your\n")
			b.WriteString("  # agent needs, its API key for example (the lists add up):\n")
			b.WriteString("  # pass:\n  #   - ANTHROPIC_API_KEY\n")
		}
		b.WriteString("  # Variables tego sets for the agent, so its temporary files and caches land in folders it may write.\n")
		b.WriteString("  set:\n")
		for _, e := range envSet {
			// The reason goes above the line: the values are absolute paths, too long to keep a column beside.
			k, v, _ := strings.Cut(e.value, "=")
			fmt.Fprintf(&b, "    # %s\n    %s: %s\n", e.why, k, strconv.Quote(v))
		}
	}
	return []byte(b.String())
}

// makeDir records that folder dir, named by the fs.write entry value, is to be created before the contract runs.
func (r *Result) makeDir(dir, value string) {
	if !slices.Contains(r.MakeDirs, dir) {
		r.MakeDirs = append(r.MakeDirs, dir)
	}
	if !slices.Contains(r.makeEntries, value) {
		r.makeEntries = append(r.makeEntries, value)
	}
}

func appendEntry(list []entry, e entry) []entry {
	for _, x := range list {
		if x.value == e.value {
			return list
		}
	}
	return append(list, e)
}

// writeList writes list as YAML list items, each value quoted and its reason aligned in one column.
func writeList(b *strings.Builder, indent string, list []entry) {
	width := 0
	for _, e := range list {
		width = max(width, len(strconv.Quote(e.value)))
	}
	for _, e := range list {
		fmt.Fprintf(b, "%s- %-*s   # %s\n", indent, width, strconv.Quote(e.value), e.why)
	}
}

func exists(p string) bool {
	_, err := os.Stat(p)
	return err == nil
}

// writeEntry turns one --write folder into its fs.write entry: ./rel/ inside the project, an absolute path outside
// it. A missing folder inside the project is returned in mk to be created; a missing one outside it is a usage error.
// Dir is resolved (Options.Dir), so an absolute (or ~/) folder is placed with the links of its existing part resolved
// (resolveExisting): one spelled through the link a person reached the project by is inside it, as it is when typed
// relative, and one that a link leads out of the project is outside it. A relative one is placed as typed.
func writeEntry(o Options, w string) (value, mk string, err error) {
	w = strings.TrimSpace(w)
	if w == "" {
		return "", "", usagef("--write needs a folder")
	}
	if strings.ContainsAny(w, "*?[") {
		return "", "", usagef("--write %q: a write entry is a path, never a glob", w)
	}
	p := w
	if o.Home != "" && (p == "~" || strings.HasPrefix(p, "~/")) {
		p = filepath.Join(o.Home, strings.TrimPrefix(p, "~"))
	}
	typedAbs := filepath.IsAbs(p)
	if !typedAbs {
		p = filepath.Join(o.Dir, p)
	}
	p = filepath.Clean(p)
	at := p
	if typedAbs {
		at = resolveExisting(p)
	}
	rel, rerr := filepath.Rel(o.Dir, at)
	inside := rerr == nil && rel != ".." && !strings.HasPrefix(rel, "../")
	fi, serr := os.Stat(p)
	switch {
	case serr == nil:
	case errors.Is(serr, os.ErrNotExist) && inside:
		mk = filepath.Join(o.Dir, rel)
	case errors.Is(serr, os.ErrNotExist) && at != p:
		return "", "", usagef("--write %s: %s does not exist, and a symbolic link on its way places it at %s, outside the project; init creates a missing folder only inside the project", w, p, at)
	case errors.Is(serr, os.ErrNotExist):
		return "", "", usagef("--write %s: %s does not exist; init creates a missing folder only inside the project", w, p)
	default:
		return "", "", usagef("--write %s: %v", w, serr)
	}
	isDir := serr != nil || fi.IsDir()
	if inside {
		value = "./"
		if rel != "." {
			value += filepath.ToSlash(rel)
			if isDir {
				value += "/"
			}
		}
		return value, mk, nil
	}
	value = p
	if isDir && !strings.HasSuffix(value, "/") {
		value += "/"
	}
	return value, mk, nil
}

// resolveExisting is the absolute path p with the symbolic links of its longest part that resolves followed
// (filepath.EvalSymlinks) and the names past that part kept as written: where p is, or is made once its missing
// folders are. A name kept as written may still be a link (one leading nowhere yet), which Create refuses by name
// when it would make a folder through it.
func resolveExisting(p string) string {
	var rest []string
	for q := p; ; q = filepath.Dir(q) {
		if r, err := filepath.EvalSymlinks(q); err == nil {
			return filepath.Join(append([]string{r}, rest...)...)
		}
		if filepath.Dir(q) == q {
			return p
		}
		rest = append([]string{filepath.Base(q)}, rest...)
	}
}

// secretFolderIn names the first built-in deny_read path under home that the fs.write value v is, holds or lies
// inside, or "" for none; a relative value is taken from the project directory dir (a project at ~ itself).
func secretFolderIn(home, dir, v string) string {
	if home == "" {
		return ""
	}
	p := filepath.FromSlash(v)
	if !filepath.IsAbs(p) {
		p = filepath.Join(dir, p)
	}
	p = filepath.Clean(p)
	for _, rel := range agent.BuiltInDenyRead() {
		full := filepath.Join(home, rel)
		if p == full || strings.HasPrefix(p, full+"/") || strings.HasPrefix(full, p+"/") {
			return rel
		}
	}
	return ""
}

// hostEntries turns one --allow-host into its net.allow entries: @group expands from pkg/spec/presets, a host with
// no port gets :443, and a unix: socket path passes through.
func hostEntries(h string) ([]entry, error) {
	h = strings.ToLower(strings.TrimSpace(h))
	switch {
	case h == "":
		return nil, usagef("--allow-host needs a host")
	case strings.HasPrefix(h, "@"):
		gs, err := presets.HostGroups()
		if err != nil {
			return nil, err
		}
		var known []string
		for _, g := range gs {
			known = append(known, "@"+g.Name)
			if "@"+g.Name == h {
				var out []entry
				for _, x := range g.Hosts {
					out = append(out, entry{x, "--allow-host " + h})
				}
				return out, nil
			}
		}
		return nil, usagef("unknown host group %q; the groups are %s", h, strings.Join(known, ", "))
	case strings.HasPrefix(h, "unix:"):
		return []entry{{h, "--allow-host"}}, nil
	case strings.Contains(h, "://") || strings.ContainsAny(h, "/ \t"):
		return nil, usagef("--allow-host %q: write a host or host:port, not a URL", h)
	}
	host, port, defaulted := h, "443", true
	switch {
	case strings.HasPrefix(h, "["): // [v6]:port
		if i := strings.LastIndex(h, "]:"); i > 0 {
			host, port, defaulted = h[:i+1], h[i+2:], false
		}
	case strings.Count(h, ":") > 1: // a bare IPv6 address takes no port: write [v6]:port for one
		host = "[" + h + "]"
	case strings.Count(h, ":") == 1:
		host, port, _ = strings.Cut(h, ":")
		defaulted = false
	}
	if n, err := strconv.Atoi(port); err != nil || n < 1 || n > 65535 {
		return nil, usagef("--allow-host %q: the port must be 1 to 65535", h)
	}
	if host == "" {
		return nil, usagef("--allow-host %q: the host is empty", h)
	}
	why := "--allow-host"
	if defaulted {
		why = "--allow-host, port 443 (HTTPS) by default"
	}
	return []entry{{host + ":" + port, why}}, nil
}

// commandArgv is the contract's command for one --command line: its words when it holds no shell syntax, else
// /bin/sh -c line.
func commandArgv(line string) []string {
	line = strings.TrimSpace(line)
	if strings.ContainsAny(line, "|&;<>()$`\\\"'*?[]#~=%{}\n") {
		return []string{"/bin/sh", "-c", line}
	}
	return strings.Fields(line)
}

// demoCommand is the command init writes when --command is not given: a line per chosen preset that shows its
// promise with sh alone. no-prod has no line: sh holds no network client, and tego test shows that channel.
func demoCommand(has func(string) bool, firstWrite string) string {
	var parts []string
	if has("repo-only-writes") && firstWrite != "" {
		in := strings.TrimSuffix(firstWrite, "/") + "/tego-hello.txt"
		if !strings.HasSuffix(firstWrite, "/") {
			in = firstWrite
		}
		parts = append(parts,
			fmt.Sprintf("echo hello > %s && echo %s", shQuote(in), shQuote("wrote "+in+": allowed")),
			"(echo x > ./tego-outside.txt) && echo 'wrote ./tego-outside.txt: NOT refused' || echo 'write ./tego-outside.txt: refused by repo-only-writes'")
	}
	if has("no-secrets") {
		parts = append(parts, `[ -n "${AWS_SECRET_ACCESS_KEY}${GITHUB_TOKEN}${ANTHROPIC_API_KEY}${OPENAI_API_KEY}" ] && echo 'a secret variable reached the agent' || echo 'no secret variable reached the agent: no-secrets'`)
	}
	if len(parts) == 0 {
		parts = append(parts, "echo 'tego: replace command: in agent.yaml with your agent'")
	}
	return strings.Join(parts, "\n")
}

func shQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

// askPath is an fs.ask_read entry as typed: ~/ expanded to Home, an absolute path kept, anything else relative to
// the project ("./").
func askPath(o Options, a string) string {
	switch {
	case strings.HasPrefix(a, "~/") && o.Home != "":
		return filepath.Join(o.Home, a[2:]) + trailingSlash(a)
	case filepath.IsAbs(a), strings.HasPrefix(a, "./"):
		return a
	}
	return "./" + a
}

func trailingSlash(a string) string {
	if strings.HasSuffix(a, "/") {
		return "/"
	}
	return ""
}

// agentNeed is what an agent needs to run under restrictive presets.
type agentNeed struct {
	writes, hosts, env, pass []entry
	// made maps a write entry to the absolute folder to create for it; ignore are .gitignore lines.
	made   map[string]string
	ignore []string
}

// agentNeedsOf is what the agent argv starts needs: its own folder in the project (so the presets need not open the
// home), its terminal devices (each stores nothing), its socket folder, its model host and its login variables. Claude
// Code and Codex are known, in examples/agents' claude-code-interactive.yaml and codex-chatgpt.yaml; any other program
// needs nothing here.
func agentNeedsOf(o Options, argv []string) agentNeed {
	n := agentNeed{made: map[string]string{}}
	if len(argv) == 0 {
		return n
	}
	own := func(sub, envKey, why string) {
		dir := filepath.Join(o.Dir, ".tego", sub)
		v := "./.tego/" + sub + "/"
		n.writes = append(n.writes, entry{v, why})
		n.made[v] = dir
		n.env = append(n.env, entry{envKey + "=" + dir, why})
		n.ignore = append(n.ignore, ".tego/"+sub+"/")
	}
	switch filepath.Base(argv[0]) {
	case "claude":
		own("claude", "CLAUDE_CONFIG_DIR", "Claude Code's own folder: its login, settings and sessions")
		socks := "/run/user/" + strconv.Itoa(os.Getuid()) + "/cc-socks/"
		n.writes = append(n.writes, entry{"/dev/null", "its Bash tool redirects into it"},
			entry{"/dev/tty", "the full-screen interface draws there"}, entry{socks, "Claude Code's session sockets"})
		n.made[socks] = filepath.Clean(socks)
		n.hosts = append(n.hosts, entry{"api.anthropic.com:443", "Claude Code's model"})
		n.env = append(n.env, entry{"DISABLE_AUTOUPDATER=1", "no self-update inside the run"},
			entry{"CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC=1", "no optional network calls"})
		n.pass = append(n.pass, entry{"CLAUDE_CODE_OAUTH_TOKEN", "Claude Code's login (claude setup-token)"},
			entry{"ANTHROPIC_API_KEY", "or an API key"})
	case "codex":
		own("codex", "CODEX_HOME", "Codex's own folder: its login and settings")
		n.writes = append(n.writes, entry{"/dev/null", "its tools redirect into it"}, entry{"/dev/tty", "the full-screen interface draws there"},
			entry{"/dev/ptmx", "Codex runs each command in a pseudo-terminal"}, entry{"/dev/pts/", "the same pseudo-terminals"})
		n.hosts = append(n.hosts, entry{"chatgpt.com:443", "Codex's model (ChatGPT sign-in)"},
			entry{"auth.openai.com:443", "Codex's sign-in"})
		n.pass = append(n.pass, entry{"OPENAI_API_KEY", "Codex with an API key"})
	}
	return n
}
