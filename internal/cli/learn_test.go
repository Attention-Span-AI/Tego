// learnFixtureRun writes fixture into a run directory, with the fixture's /home/user written home, and returns it.
func learnFixtureRun(t *testing.T, fixture, home string) string {
	t.Helper()
	f, err := os.Open(fixture)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = f.Close() }()
	var in io.Reader = f
	if strings.HasSuffix(fixture, ".gz") {
		zr, err := gzip.NewReader(f)
		if err != nil {
			t.Fatal(err)
		}
		defer func() { _ = zr.Close() }()
		in = zr
	}
	data, err := io.ReadAll(in)
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	data = bytes.ReplaceAll(data, []byte("/home/user"), []byte(home))
	if err := os.WriteFile(filepath.Join(dir, ledger.EventsFile), data, 0o600); err != nil {
		t.Fatal(err)
	}
	return dir
}

// resolvedTemp is t.TempDir with its symlinks followed, which compile's own resolution makes the spelling of every
// path it prints.
func resolvedTemp(t *testing.T) string {
	t.Helper()
	dir, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	return dir
}

func TestLearnPrintsAProposal(t *testing.T) {
	dir := learnFixtureRun(t, learnClaudeFixture, "/home/user")
	code, out, errs := run(t, "learn", dir)
	if code != identity.ExitOK {
		t.Fatalf("exit %d (stderr %q)", code, errs)
	}
	for _, want := range []string{"# Proposed boundary contract, generated by `tego learn` from run r-3f9c2a1b-0dlxvjfyhw2x3-60qh2h",
		"# This is a PROPOSAL for a person to review", "# Left out, and why:", "version: 0\n", `command: ["claude"]`,
		`- "/dev/tty"`, `- "tcp://160.79.104.10:443"`, "never the host name it asked for"} {
		if !strings.Contains(out, want) {
			t.Errorf("the proposal lacks %q\n%s", want, out)
		}
	}
	if !strings.Contains(errs, "left out of the proposal") {
		t.Errorf("stderr does not say that actions were left out: %q", errs)
	}
	// It reads the record and nothing else: the run directory is as it was.
	if _, err := os.Stat(filepath.Join(dir, "lock")); err == nil {
		t.Error("learn left a lock in the run directory")
	}
}

// TestLearnOutIsANewPrivateFile: --out writes a new file, mode 0600, and never replaces one, a link included.
func TestLearnOutIsANewPrivateFile(t *testing.T) {
	dir := learnFixtureRun(t, learnClaudeFixture, "/home/user")
	out := filepath.Join(t.TempDir(), "proposed.yaml")
	code, stdout, errs := run(t, "learn", dir, "--out", out)
	if code != identity.ExitOK {
		t.Fatalf("exit %d (stderr %q)", code, errs)
	}
	if stdout != "" {
		t.Errorf("--out also printed the proposal: %q", stdout)
	}
	fi, err := os.Stat(out)
	if err != nil {
		t.Fatal(err)
	}
	if fi.Mode().Perm() != 0o600 {
		t.Errorf("mode %v, want 0600", fi.Mode().Perm())
	}
	if !strings.Contains(errs, "a proposal for you to review") || !strings.Contains(errs, "tego compile "+out) {
		t.Errorf("stderr does not say what to do next: %q", errs)
	}
	first, _ := os.ReadFile(out)

	code, _, errs = run(t, "learn", dir, "--out", out)
	if code != identity.ExitFinding || !strings.Contains(errs, "[exists]") {
		t.Errorf("an existing file: exit %d, stderr %q; want 1 [exists]", code, errs)
	}
	if again, _ := os.ReadFile(out); !bytes.Equal(first, again) {
		t.Error("an existing proposal was overwritten")
	}

	// A link at the name, dangling or not, is refused and its target is left alone.
	target := filepath.Join(t.TempDir(), "victim")
	link := filepath.Join(t.TempDir(), "link.yaml")
	if err := os.Symlink(target, link); err != nil {
		t.Fatal(err)
	}
	if code, _, errs = run(t, "learn", dir, "--out", link); code != identity.ExitFinding {
		t.Errorf("a link: exit %d, stderr %q; want 1", code, errs)
	}
	if _, err := os.Lstat(target); err == nil {
		t.Error("learn wrote through a link")
	}
	// A directory that is not there is an I/O error of tego's own.
	if code, _, errs = run(t, "learn", dir, "--out", filepath.Join(t.TempDir(), "no", "such", "dir.yaml")); code != identity.ExitError || !strings.Contains(errs, "[io]") {
		t.Errorf("a missing directory: exit %d, stderr %q; want 125 [io]", code, errs)
	}
}

// TestLearnWorkspace: --workspace names where writes may be allowed; the default is the run's working directory.
func TestLearnWorkspace(t *testing.T) {
	root := resolvedTemp(t)
	dir := learnFixtureRun(t, learnClaudeFixture, root)
	_, out, _ := run(t, "learn", dir)
	if strings.Contains(out, `"`+root+"/.cache/tego-workdir/poc-run/home-claude/.claude/\"") {
		t.Errorf("a write outside the run's working directory was allowed by default\n%s", out)
	}
	code, out, errs := run(t, "learn", dir, "--workspace", filepath.Join(root, ".cache", "tego-workdir", "poc-run"))
	if code != identity.ExitOK {
		t.Fatalf("exit %d (stderr %q)", code, errs)
	}
	if want := `- "` + root + `/.cache/tego-workdir/poc-run/home-claude/.claude/"`; !strings.Contains(out, want) {
		t.Errorf("the proposal lacks %q under the wider workspace\n%s", want, out)
	}
	if strings.Contains(out, `- "/run/user/1000/cc-socks/"`) {
		t.Errorf("a directory outside the named workspace was allowed\n%s", out)
	}
	for _, bad := range []string{"/", "//", "/x/.."} {
		if code, _, errs = run(t, "learn", dir, "--workspace", bad); code != identity.ExitUsage || !strings.Contains(errs, "[usage]") {
			t.Errorf("--workspace %q: exit %d, stderr %q; want a usage error", bad, code, errs)
		}
	}
	// The lines name paths the kernel's way, every link resolved, so a workspace named through a link is the same
	// directory: it was compared as spelled, and nothing the run wrote was under it.
	workspace := filepath.Join(root, ".cache", "tego-workdir", "poc-run")
	if err := os.MkdirAll(workspace, 0o700); err != nil {
		t.Fatal(err)
	}
	link := filepath.Join(resolvedTemp(t), "project")
	if err := os.Symlink(workspace, link); err != nil {
		t.Fatal(err)
	}
	code, out, errs = run(t, "learn", dir, "--workspace", link)
	if code != identity.ExitOK {
		t.Fatalf("--workspace through a link: exit %d (stderr %q)", code, errs)
	}
	if want := `- "` + root + `/.cache/tego-workdir/poc-run/home-claude/.claude/"`; !strings.Contains(out, want) {
		t.Errorf("--workspace through a link: the proposal lacks %q\n%s", want, out)
	}
}

func TestLearnUsage(t *testing.T) {
	dir := learnFixtureRun(t, learnClaudeFixture, "/home/user")
	for _, tc := range []struct {
		name string
		args []string
		code int
		want string
	}{
		{"no run", []string{"learn"}, identity.ExitUsage, "exactly one run id or run directory"},
		{"two runs", []string{"learn", dir, dir}, identity.ExitUsage, "exactly one run id"},
		{"a bad run id", []string{"learn", "r-1"}, identity.ExitUsage, "[usage]"},
		{"an unknown flag", []string{"learn", dir, "--bogus"}, identity.ExitUsage, "flag provided but not defined"},
		{"a directory with no record", []string{"learn", t.TempDir()}, identity.ExitUsage, "[usage]"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			code, out, errs := run(t, tc.args...)
			if code != tc.code || !strings.Contains(errs, tc.want) || out != "" {
				t.Errorf("exit %d stdout %q stderr %q; want %d and %q", code, out, errs, tc.code, tc.want)
			}
		})
	}
}

