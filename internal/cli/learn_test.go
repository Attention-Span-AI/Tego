// TestLearnNeverProposesTegosOwnState: a run whose working directory holds the ledger root and the run's own record
// is not given a write entry that is or covers them, whatever it wrote.
func TestLearnNeverProposesTegosOwnState(t *testing.T) {
	root := gcRoot(t)
	project := filepath.Dir(root) // holds the ledger root, as a project does when ledger_root is inside it
	id := learnWriteRun(t, root, project, func(w *ledger.Writer) {
		learnWrite(t, w, filepath.Join(project, "out", "a.txt"))
		learnWrite(t, w, filepath.Join(root, "other-run", "events.jsonl")) // another run's record
		learnWrite(t, w, filepath.Join(project, "notes.txt"))              // makes the project itself an entry: it holds the root
	})
	code, out, errs := run(t, "learn", id)
	if code != identity.ExitOK {
		t.Fatalf("exit %d (stderr %q)", code, errs)
	}
	if !strings.Contains(out, `- "`+project+`/out/"`) {
		t.Errorf("the ordinary write was not proposed\n%s", out)
	}
	for _, bad := range []string{`- "` + project + `/"`, `- "` + root + `/`} {
		if strings.Contains(out, bad) {
			t.Errorf("the proposal allows %s, which is or holds tego's own state\n%s", bad, out)
		}
	}
	if !strings.Contains(out, "tego's own state directory "+root) {
		t.Errorf("the proposal does not say why they were left out\n%s", out)
	}
}

// TestLearnWarnsWhenTheFileLiesInsideItself: tego refuses a contract the agent could rewrite, so a proposal written
