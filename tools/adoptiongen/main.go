// adoptiongen derives compact pinned-object checks from the committed ELF files.
// It uses the same cilium parser as the full loader, outside the launcher's path.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/cilium/ebpf"

	"github.com/attention-span-ai/tego/internal/bpf/adoptionmeta"
)

func main() {
	dir := flag.String("dir", "internal/bpf", "directory containing the committed ELF files")
	out := flag.String("output", "internal/bpf/adoption_specs_gen.go", "generated Go registry")
	flag.Parse()
	if err := generate(*dir, *out); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(dir, output string) error {
	files, err := filepath.Glob(filepath.Join(dir, "*_bpfe[lb].o"))
	if err != nil {
		return err
	}
	sort.Strings(files)
	var result bytes.Buffer
	fmt.Fprint(&result, "// SPDX-License-Identifier: Apache-2.0\n\n// Code generated by adoptiongen; DO NOT EDIT.\n\n//go:build tegobpf\n\npackage bpf\n\nvar adoptionMetadata = map[[32]byte]string{\n")
	seen := make(map[[sha256.Size]byte]bool)
	for _, file := range files {
		if testOnly(filepath.Base(file)) {
			continue // an integration-only object is never in a production binding
		}
		raw, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		sum := sha256.Sum256(raw)
		if seen[sum] {
			continue
		}
		seen[sum] = true
		spec, err := ebpf.LoadCollectionSpecFromReader(bytes.NewReader(raw))
		if err != nil {
			return fmt.Errorf("%s: %w", file, err)
		}
		metadata, err := adoptionmeta.Project(spec)
		if err != nil {
			fmt.Fprintf(&result, "// %s: full loader required (%s).\n", filepath.Base(file), err)
			continue
		}
		encoded, err := json.Marshal(metadata)
		if err != nil {
			return fmt.Errorf("%s: %w", file, err)
		}
		fmt.Fprintf(&result, "// %s\n%#v: %q,\n", filepath.Base(file), sum, encoded)
	}
	if len(seen) == 0 {
		return fmt.Errorf("adoptiongen: no production ELF files in %s", dir)
	}
	fmt.Fprintln(&result, "}")
	formatted, err := format.Source(result.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(output, formatted, 0o644)
}

// testOnly reports whether a compiled object is one of the bindings internal/bpf/gen.go builds with -tags
// integration,tegobpf only: the plane's test fill and ADR 0048 P2's K0 probe (bpf/testonly).
func testOnly(name string) bool {
	return strings.HasPrefix(name, "planetestfill_") || strings.HasPrefix(name, "pinfacts")
}
