package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/types"
	"sort"
	"strings"
)

// edgeSet is the descriptor edge list (ADR 0023 A6) as it is gathered over the main build configurations: every
// exported API of a product package, the sys owner's files included, that takes or returns a bare descriptor
// number by F8's shape, with the packages that use it. A user is a package whose code names the API's object, a
// function or a method (an interface's method when called through the interface), so a method of the same name
// on another type is not one. The migration order follows the edges: a producer changes its API no later than
// the commit that migrates its consumer.
type edgeSet map[edgeAPI]map[string]bool

type edgeAPI struct{ pkg, sym string }

// Edges is the edge list of the worlds given.
func Edges(worlds []*typedWorld) []string {
	es := edgeSet{}
	for _, w := range worlds {
		es.add(w)
	}
	return es.lines()
}

// add gathers one world's APIs and their users.
func (es edgeSet) add(w *typedWorld) {
	objs := map[types.Object]edgeAPI{}
	api := func(p *typedPkg, def *ast.Ident, sym string) {
		a := edgeAPI{p.dir, sym}
		objs[p.info.Defs[def]] = a
		if es[a] == nil {
			es[a] = map[string]bool{}
		}
	}
	for _, p := range w.pkgs {
		if ExemptPackage(p.path) {
			continue
		}
		for _, f := range p.files {
			for _, d := range f.Decls {
				switch x := d.(type) {
				case *ast.FuncDecl:
					sym := x.Name.Name
					if x.Recv != nil && len(x.Recv.List) > 0 {
						sym = recvName(x.Recv.List[0].Type) + "." + sym
					}
					if _, bad := numberShape(p.info, x.Name.Name, x.Type); bad && ast.IsExported(sym) && x.Name.IsExported() {
						api(p, x.Name, sym)
					}
				case *ast.GenDecl:
					for _, sp := range x.Specs {
						ts, ok := sp.(*ast.TypeSpec)
						if !ok || !ts.Name.IsExported() {
							continue
						}
						it, ok := ts.Type.(*ast.InterfaceType)
						if !ok {
							continue
						}
						for _, m := range it.Methods.List {
							ft, ok := m.Type.(*ast.FuncType)
							if !ok {
								continue
							}
							for _, n := range m.Names {
								if _, bad := numberShape(p.info, n.Name, ft); bad && n.IsExported() {
									api(p, n, ts.Name.Name+"."+n.Name)
								}
							}
						}
					}
				}
			}
		}
	}
	for _, p := range w.pkgs {
		if ExemptPackage(p.path) {
			continue
		}
		for _, f := range p.files {
			ast.Inspect(f, func(n ast.Node) bool {
				if id, ok := n.(*ast.Ident); ok {
					obj := p.info.Uses[id]
					if fn, ok := obj.(*types.Func); ok {
						obj = fn.Origin()
					}
					if a, ok := objs[obj]; ok && a.pkg != p.dir {
						es[a][p.dir] = true
					}
				}
				return true
			})
		}
	}
}

// lines is the edge list, sorted: "package API users" ("-": none outside its own package).
func (es edgeSet) lines() []string {
	var out []string
	for a, us := range es {
		c := "-"
		if len(us) > 0 {
			c = strings.Join(sortedKeys(us), ",")
		}
		out = append(out, fmt.Sprintf("%s %s %s", a.pkg, a.sym, c))
	}
	sort.Strings(out)
	return out
}

func dirOf(f string) string {
	d, _ := splitDir(f)
	return d
}

// edgeProblems is A6's edge rule on the list: a package baseline.txt does not list is migrated, so it uses no
// other package's API that takes or returns a bare descriptor number; it would hold, or pass back to an
// unmigrated helper, a number no owner of its own holds. The producer gives an owner, or lends
// one, no later than the commit that migrates the consumer.
func edgeProblems(edges []string, base Baseline) []string {
	var out []string
	for _, e := range edges {
		f := strings.Fields(e)
		if len(f) != 3 || f[2] == "-" {
			continue
		}
		for _, u := range strings.Split(f[2], ",") {
			if _, listed := base[u]; !listed {
				out = append(out, fmt.Sprintf("A6: %s is migrated (baseline.txt does not list it) but uses %s.%s, which takes or returns a bare descriptor number: give an owner or lend one there first (ADR 0023 A6, F8)", u, f[0], f[1]))
			}
		}
	}
	return out
}

// FormatEdges writes edges.txt.
func FormatEdges(lines []string) []byte {
	var b bytes.Buffer
	b.WriteString("# Generated by `go run ./tools/fdcheck -edges -w` (ADR 0023 A6): producer package, exported API that takes or\n")
	b.WriteString("# returns a bare descriptor number (F8's shape), and the packages that use it (\"-\": none outside its own).\n")
	b.WriteString("# A producer gives an owner or lends one no later than the commit that migrates its consumer. Do not edit; regenerate.\n")
	for _, l := range lines {
		b.WriteString(l + "\n")
	}
	return b.Bytes()
}
